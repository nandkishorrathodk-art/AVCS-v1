SUPPORTED_CHARACTERS = "".join(sorted(GLYPHS))


def draw_bitmap_text(
    draw: ImageDraw.ImageDraw,
    xy: tuple[int, int],
    text: str,
    fill: tuple[int, int, int],
    max_width: int,
) -> tuple[int, int, int, int]:
    """Draw uppercase 5x7 glyphs at native pixel size and return pixel bounds."""
    normalized = text.upper()
    unsupported = sorted(set(normalized) - GLYPHS.keys())
    if unsupported:
        raise ValueError(f"Unsupported bitmap glyph(s): {''.join(unsupported)}")

    x0, y0 = xy
    cursor_x = x0
    drawn = 0
    for char in normalized:
        glyph = GLYPHS[char]
        glyph_width = 5
        if cursor_x + glyph_width > x0 + max_width:
            break
        for row, bits in enumerate(glyph):
            for col, bit in enumerate(bits):
                if bit == "1":
                    draw.point((cursor_x + col, y0 + row), fill=fill)
        cursor_x += 6
        drawn += 1
    return (x0, y0, max(x0, cursor_x - 1), y0 + 6) if drawn else (x0, y0, x0, y0)
